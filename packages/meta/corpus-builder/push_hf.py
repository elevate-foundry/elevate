#!/usr/bin/env python3
"""push_hf.py - publish the extracted corpus as a (private) Hugging Face dataset.

Reads out/corpus.jsonl (produced by extract.mjs) and uploads it, plus out/stats.json
as a dataset card appendix, to a Hugging Face dataset repo.

Prerequisites:
    pip install huggingface_hub
    export HF_TOKEN=hf_xxx           # a token with write access
    # or: huggingface-cli login

Usage:
    python push_hf.py --repo-id elevate-foundry/elevate-corpus [--public]
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = Path(os.environ.get("OUT_DIR", HERE / "out"))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo-id", required=True, help="e.g. elevate-foundry/elevate-corpus")
    ap.add_argument("--public", action="store_true", help="create a public dataset (default: private)")
    args = ap.parse_args()

    corpus = OUT / "corpus.jsonl"
    stats_path = OUT / "stats.json"
    if not corpus.exists():
        print(f"error: {corpus} not found — run ./clone.sh && node extract.mjs first", file=sys.stderr)
        return 1

    token = os.environ.get("HF_TOKEN") or os.environ.get("HUGGING_FACE_HUB_TOKEN")
    if not token:
        print("error: set HF_TOKEN (a write token) or run `huggingface-cli login`", file=sys.stderr)
        return 1

    try:
        from huggingface_hub import HfApi
    except ImportError:
        print("error: pip install huggingface_hub", file=sys.stderr)
        return 1

    stats = json.loads(stats_path.read_text()) if stats_path.exists() else {}
    card = f"""---
license: other
tags:
- code
- elevate-foundry
---

# elevate-foundry corpus

Source code + docs extracted from the **native (non-fork)** public repositories of
`github.com/elevate-foundry`, for training/fine-tuning a model in the org's voice.

- files: {stats.get('files', '?')}
- bytes: {stats.get('totalBytes', '?')}
- est. tokens: {stats.get('estTokensHuman', '?')}
- repos: {stats.get('repos', '?')}

Each line of `corpus.jsonl` is one file: `{{repo, path, lang, bytes, sha256, text}}`.
Generated by `corpus-builder/extract.mjs`; provenance is recorded in the
exposure-toolkit SOC 2 audit trail.
"""

    api = HfApi(token=token)
    api.create_repo(repo_id=args.repo_id, repo_type="dataset", private=not args.public, exist_ok=True)
    api.upload_file(
        path_or_fileobj=str(corpus),
        path_in_repo="corpus.jsonl",
        repo_id=args.repo_id,
        repo_type="dataset",
    )
    if stats_path.exists():
        api.upload_file(
            path_or_fileobj=str(stats_path),
            path_in_repo="stats.json",
            repo_id=args.repo_id,
            repo_type="dataset",
        )
    (OUT / "README.md").write_text(card)
    api.upload_file(
        path_or_fileobj=str(OUT / "README.md"),
        path_in_repo="README.md",
        repo_id=args.repo_id,
        repo_type="dataset",
    )
    print(f"pushed -> https://huggingface.co/datasets/{args.repo_id} "
          f"({'public' if args.public else 'private'})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
